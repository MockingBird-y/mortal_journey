/** 取指定大境界下某灵根元素的加成数值；元素不存在返回 0。 */
export function getLinggenElementBonus(major: string, element: string): number {
  return LINGGEN_ELEMENT_BONUS_BY_MAJOR[major]?.[element] ?? 0;
}

/** 计算角色全部灵根战斗加成（金/水/火/土）。木在丹药获取时单独烘焙。 */
export function computeLinggenCombatBonuses(linggen: readonly string[], major: string) {
  const has = (el: string) => linggen.includes(el);
  return {
    critDmgBonus: has("金") ? getLinggenElementBonus(major, "金") : 0,
    cooldownReduce: has("水") ? getLinggenElementBonus(major, "水") : 0,
    healMult: has("火") ? 1 + getLinggenElementBonus(major, "火") / 100 : 1,
    shieldMult: has("土") ? 1 + getLinggenElementBonus(major, "土") / 100 : 1,
  };
}

