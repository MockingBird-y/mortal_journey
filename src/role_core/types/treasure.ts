// ═══════════════════════════════════════════════════════════════════════════
// 随机分配
// ═══════════════════════════════════════════════════════════════════════════

export function rollTreasureFunction(grade: ItemGrade): TreasureSpecialEffect {
  const pool = TREASURE_EFFECT_CATALOG[grade] ?? TREASURE_EFFECT_CATALOG["下品"];
  const idx = Math.floor(Math.random() * pool.length);
  return { ...pool[idx] };
}

